"""Local inference and research artifact API. Never trains inside a request."""

from __future__ import annotations

import json
import logging
import os
import threading
import time
import uuid
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd

try:
    from fastapi import FastAPI as Application
    from fastapi import HTTPException, Request

    FRAMEWORK = "FastAPI"
except ImportError:
    from starlette.exceptions import HTTPException
    from starlette.requests import Request

    from forgeml.http_app import StarletteApplication as Application

    FRAMEWORK = "Starlette + Pydantic (offline fallback)"
from pydantic import BaseModel, ConfigDict, Field
from starlette.responses import FileResponse, JSONResponse, PlainTextResponse
from starlette.staticfiles import StaticFiles

ROOT = Path(__file__).resolve().parents[1]
LOG = logging.getLogger("forgeml.api")


class Transaction(BaseModel):
    """Only fields available at scoring time; outcome labels are prohibited."""

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)
    TransactionID: int = Field(ge=0)
    TransactionDT: float = Field(ge=0)
    TransactionAmt: float = Field(gt=0, le=1e9)
    card1: int | None = Field(default=None, ge=0)
    card2: int | None = Field(default=None, ge=0)
    card3: int | None = Field(default=None, ge=0)
    card4: str | None = Field(default=None, max_length=64)
    card5: int | None = Field(default=None, ge=0)
    card6: str | None = Field(default=None, max_length=64)
    addr1: int | None = Field(default=None, ge=0)
    addr2: int | None = Field(default=None, ge=0)
    DeviceInfo: str | None = Field(default=None, max_length=256)
    ProductCD: str | None = Field(default=None, max_length=32)
    P_emaildomain: str | None = Field(default=None, max_length=256)
    R_emaildomain: str | None = Field(default=None, max_length=256)
    DeviceType: str | None = Field(default=None, max_length=64)


class Batch(BaseModel):
    model_config = ConfigDict(extra="forbid")
    transactions: list[Transaction] = Field(min_length=1, max_length=512)


class ReplayRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    batch_size: int = Field(default=100, ge=10, le=1000)
    label_delay: int = Field(default=2, ge=0, le=1000, description="Delay in replay batches")
    induce_shift: bool = False


class GovernanceRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    version: str | None = Field(default=None, max_length=128)


def create_app(artifact_dir: Path | None = None) -> Application:
    """Application factory, with isolated artifact directory for tests."""
    artifacts = Path(artifact_dir or os.environ.get("FORGEML_ARTIFACT_DIR", ROOT / "artifacts"))
    app = Application(
        title="ForgeML Pro",
        version="0.1.0",
        description="Historical fraud simulation; synthetic fixtures are explicitly labeled.",
    )
    app.state.bundle = None
    app.state.bundle_stamp = None
    app.state.telemetry = {"requests": 0, "errors": 0, "predictions": 0, "latency_ms": []}
    app.state.lock = threading.RLock()

    def read_json(filename: str, default: Any = None):
        path = artifacts / filename
        if not path.is_file():
            if default is not None:
                return default
            raise HTTPException(503, f"Artifact {filename} unavailable; run scripts/train.py first.")
        with path.open(encoding="utf-8") as handle:
            return json.load(handle)

    def get_bundle():
        path = artifacts / "bundle.joblib"
        if not path.is_file():
            raise HTTPException(503, "Model bundle unavailable; run offline training first.")
        stamp = path.stat().st_mtime_ns
        with app.state.lock:
            if app.state.bundle is None or app.state.bundle_stamp != stamp:
                # joblib must only load trusted artifacts generated by this repository.
                app.state.bundle = joblib.load(path)
                app.state.bundle_stamp = stamp
            return app.state.bundle

    @app.middleware("http")
    async def telemetry(request: Request, call_next):
        started = time.perf_counter()
        request_id = str(uuid.uuid4())
        request.state.request_id = request_id
        try:
            response = await call_next(request)
        except Exception:
            LOG.exception("request_failed request_id=%s path=%s", request_id, request.url.path)
            response = JSONResponse({"detail": "Internal service error", "request_id": request_id}, status_code=500)
        elapsed = (time.perf_counter() - started) * 1000
        with app.state.lock:
            stats = app.state.telemetry
            stats["requests"] += 1
            stats["errors"] += int(response.status_code >= 400)
            stats["latency_ms"].append(elapsed)
            del stats["latency_ms"][:-10000]
        response.headers["X-Request-ID"] = request_id
        LOG.info(
            "request_completed request_id=%s path=%s status=%s latency_ms=%.3f",
            request_id,
            request.url.path,
            response.status_code,
            elapsed,
        )
        return response

    @app.get("/health")
    def health():
        return {"status": "ok", "service": "forgeml-pro", "framework": FRAMEWORK}

    @app.get("/ready")
    def ready():
        bundle = get_bundle()
        return {"status": "ready", "model_version": bundle["version"], "mode": bundle["mode"]}

    @app.get("/model-info")
    def model_info():
        bundle = get_bundle()
        return {
            key: bundle.get(key)
            for key in ("version", "mode", "threshold", "feature_columns", "selected_model", "policy_version")
        } | {
            "history_semantics": "Immutable offline history snapshot; requests do not mutate entity history.",
            "simulation": True,
        }

    def score(transactions: list[Transaction], request: Request):
        from forgeml.training import predict_bundle

        started = time.perf_counter()
        bundle = get_bundle()
        raw = pd.DataFrame([tx.model_dump() for tx in transactions])
        if raw.TransactionID.duplicated().any():
            raise HTTPException(422, "TransactionID must be unique within a batch.")
        probabilities = np.asarray(predict_bundle(bundle, raw), dtype=float)
        threshold = float(bundle["threshold"])
        elapsed = (time.perf_counter() - started) * 1000
        rows = []
        for tx, probability in zip(transactions, probabilities):
            if not np.isfinite(probability):
                raise HTTPException(500, "Model returned a non-finite probability.")
            risk = float(probability)
            rows.append(
                {
                    "transaction_id": tx.TransactionID,
                    "probability": risk,
                    "fraud_probability": risk,
                    "risk_category": "high" if risk >= threshold else "low",
                    "recommendation": "review" if risk >= threshold else "approve",
                    "threshold": threshold,
                    "policy_version": bundle.get("policy_version", "validation-cost-v1"),
                    "model_version": bundle["version"],
                    "request_id": request.state.request_id,
                    "latency_ms": round(elapsed, 3),
                    "mode": bundle["mode"],
                    "history_semantics": "immutable offline snapshot",
                    "explanation": None,
                }
            )
        with app.state.lock:
            app.state.telemetry["predictions"] += len(rows)
        return rows

    @app.post("/predict")
    def predict(transaction: Transaction, request: Request):
        return score([transaction], request)[0]

    @app.post("/predict-batch")
    def predict_batch(batch: Batch, request: Request):
        return {"predictions": score(batch.transactions, request), "count": len(batch.transactions)}

    @app.get("/metrics", response_class=PlainTextResponse)
    def metrics():
        with app.state.lock:
            stats = dict(app.state.telemetry)
            latencies = list(stats["latency_ms"])
        lines = [
            "# TYPE forgeml_requests_total counter",
            f"forgeml_requests_total {stats['requests']}",
            "# TYPE forgeml_errors_total counter",
            f"forgeml_errors_total {stats['errors']}",
            "# TYPE forgeml_predictions_total counter",
            f"forgeml_predictions_total {stats['predictions']}",
            "# TYPE forgeml_request_latency_ms summary",
            f"forgeml_request_latency_ms_count {len(latencies)}",
            f"forgeml_request_latency_ms_sum {sum(latencies):.6f}",
        ]
        for quantile in (0.5, 0.95):
            lines.append(
                f'forgeml_request_latency_ms{{quantile="{quantile}"}} {np.quantile(latencies, quantile) if latencies else 0:.6f}'
            )
        return "\n".join(lines) + "\n"

    @app.get("/api/report")
    def report():
        return read_json("report.json")

    @app.get("/api/examples")
    def examples():
        artifact = read_json("examples.json")
        if isinstance(artifact, list):
            return {"examples": artifact, "mode": get_bundle()["mode"]}
        return artifact

    @app.get("/api/explanations")
    def explanations():
        return read_json("explanations.json")

    @app.get("/api/graph")
    def graph():
        return read_json("report.json").get("graph", {})

    @app.get("/api/monitoring")
    def monitoring():
        result = read_json("replay.json", {}) or read_json("report.json").get("monitoring", {})
        with app.state.lock:
            stats = app.state.telemetry
            service = {
                "requests": stats["requests"],
                "errors": stats["errors"],
                "predictions": stats["predictions"],
                "p95_latency_ms": float(np.quantile(stats["latency_ms"], 0.95)) if stats["latency_ms"] else None,
            }
        return {**result, "service": service}

    @app.get("/api/governance")
    def governance():
        return read_json("registry.json", {}) or read_json("report.json").get("governance", {})

    @app.post("/api/replay")
    def replay(config: ReplayRequest):
        from forgeml.monitoring import replay as replay_engine

        source = artifacts / "replay-data.csv"
        if not source.is_file():
            raise HTTPException(503, "Replay development data unavailable; run offline training first.")
        with app.state.lock:
            result = replay_engine(
                get_bundle(),
                pd.read_csv(source),
                batch_size=config.batch_size,
                label_delay=config.label_delay,
                induced_shift=config.induce_shift,
            )
            (artifacts / "replay.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
            return result

    @app.post("/api/governance/{action}")
    def govern(action: str, config: GovernanceRequest):
        if action not in {"evaluate", "promote", "reject", "rollback"}:
            raise HTTPException(404, "Unknown governance action")
        from forgeml.governance import governance_action

        try:
            with app.state.lock:
                return governance_action(artifacts, action, version=config.version)
        except (ValueError, FileNotFoundError) as error:
            raise HTTPException(409, str(error)) from error

    frontend = ROOT / "frontend"
    if frontend.is_dir():
        app.mount("/static", StaticFiles(directory=frontend), name="static")

    @app.get("/", include_in_schema=False)
    def dashboard():
        index = frontend / "index.html"
        if not index.is_file():
            raise HTTPException(503, "Dashboard unavailable.")
        return FileResponse(index)

    return app


app = create_app()
